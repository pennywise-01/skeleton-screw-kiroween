import { NextRequest, NextResponse } from 'next/server';
import { spawn } from 'child_process';
import { z } from 'zod';
import { isDemoMode, demoAgentResponse } from '@/lib/demo';

// Schemas defined here since skeleton/lib isn't exported
const FilesSchema = z.object({
  files: z.array(z.object({ path: z.string(), content: z.string() })).min(1),
  explanation: z.string(),
});

const CodeSchema = z.object({ 
  code: z.string(), 
  explanation: z.string() 
});

const ReportSchema = z.object({ 
  report: z.string(), 
  explanation: z.string() 
});

export const maxDuration = 600;

export async function POST(req: NextRequest) {
  const { task, context, outputSchema } = (await req.json()) as {
    task: string;
    context?: string;
    outputSchema: 'files' | 'code' | 'report';
  };

  if (isDemoMode()) {
    return NextResponse.json({ ...demoAgentResponse(outputSchema, task, context), provider: 'kiro' });
  }

  const prompt = buildPrompt(task, context, outputSchema);

  // Streamed response: newline heartbeats keep the socket active while
  // kiro-cli thinks (Node kills sockets idle for 5 minutes -> "NetworkError").
  const stream = new ReadableStream({
    start(controller) {
      const encoder = new TextEncoder();
      const heartbeat = setInterval(() => {
        try {
          controller.enqueue(encoder.encode('\n'));
        } catch {
          // stream already closed
        }
      }, 15000);

      let killer: ReturnType<typeof setTimeout>;
      const finish = (payload: unknown) => {
        clearInterval(heartbeat);
        clearTimeout(killer);
        try {
          controller.enqueue(encoder.encode(JSON.stringify(payload)));
          controller.close();
        } catch {
          // client went away
        }
      };

      // Prompt as positional arg; --trust-workspace skips the blocking trust prompt
      const kiro = spawn('kiro-cli', ['chat', '--no-interactive', '--trust-workspace', prompt], {
        stdio: ['ignore', 'pipe', 'pipe'],
      });

      let stdout = '';
      let stderr = '';

      kiro.stdout.on('data', (data) => {
        stdout += data.toString();
      });

      kiro.stderr.on('data', (data) => {
        stderr += data.toString();
      });

      kiro.on('error', (err) => {
        finish({ __error: `kiro-cli not found: ${err.message}` });
      });

      kiro.on('close', (code) => {
        if (code !== 0) {
          finish({ __error: `kiro-cli exited with code ${code}: ${stderr.slice(0, 400)}` });
          return;
        }

        try {
          const output = stdout.trim();

          // Try parsing as JSON first
          try {
            const jsonMatches = output.match(/\{[\s\S]*\}/g);
            if (jsonMatches && jsonMatches.length > 0) {
              const parsed = JSON.parse(jsonMatches[jsonMatches.length - 1]);
              const schema = { files: FilesSchema, code: CodeSchema, report: ReportSchema }[outputSchema];
              const validated = schema.parse(parsed);
              finish({ ...validated, provider: 'kiro' });
              return;
            }
          } catch {
            // JSON parsing failed, treat as plain text
          }

          // Not JSON - structure the plain text response
          if (outputSchema === 'code') {
            // Documents (specs, markdown) keep the whole reply; code pulls the largest fenced block
            const wantsDoc = /spec|markdown|document/i.test(task);
            const content = wantsDoc
              ? stripWrappingFence(output)
              : (extractSingleCodeBlock(output) ?? output);
            finish({ code: content, explanation: 'AI-generated content using Kiro CLI', provider: 'kiro' });
          } else if (outputSchema === 'report') {
            finish({ report: output, explanation: 'Analysis from Kiro CLI', provider: 'kiro' });
          } else {
            const codeBlocks = extractCodeBlocks(output);
            if (codeBlocks.length > 0) {
              finish({ files: codeBlocks, explanation: 'Files generated by Kiro CLI', provider: 'kiro' });
            } else {
              finish({ __error: 'Kiro CLI did not return any code blocks' });
            }
          }
        } catch (err) {
          finish({ __error: `Kiro CLI error: ${(err as Error).message}` });
        }
      });

      // Full-project codegen can take 5-10 minutes on large specs
      killer = setTimeout(() => {
        kiro.kill();
        finish({ __error: 'Kiro CLI timed out after 10 minutes. Try a smaller spec, or split it into parts.' });
      }, 600000);
    },
  });

  return new Response(stream, {
    headers: { 'Content-Type': 'application/json; charset=utf-8', 'X-Accel-Buffering': 'no' },
  });
}

function buildPrompt(task: string, context: string | undefined, schema: string): string {
  if (schema === 'files') {
    return `${task}\n\n${context ?? ''}\n\nFor EACH file, output one fenced code block with the language and path on the fence line, like \`\`\`js:handler.js or \`\`\`json:package.json. Documentation goes in a \`\`\`md:README.md block. Do NOT put prose or documentation into code files.`;
  } else if (schema === 'code') {
    const wantsDoc = /spec|markdown|document/i.test(task);
    const instruction = wantsDoc
      ? 'Return the complete document as plain markdown text. Do NOT wrap it in code fences.'
      : 'IMPORTANT: Return the COMPLETE fixed file inside ONE markdown code block (```). No explanation, no partial snippets, no text outside the code block.';
    return `${task}\n\n${context ?? ''}\n\n${instruction}`;
  } else {
    return `${task}\n\n${context ?? ''}`;
  }
}

function stripWrappingFence(text: string): string {
  const trimmed = text.trim();
  // Only unwrap when the ENTIRE reply is one fenced block
  const whole = /^```[\w.+#-]*\s*\n([\s\S]*)\n```$/.exec(trimmed);
  return whole ? whole[1].trim() : trimmed;
}

function extractSingleCodeBlock(text: string): string | null {
  const regex = /```(?:[\w.+#-]+)?\s*\n([\s\S]*?)```/g;
  let largest: string | null = null;
  let match;
  while ((match = regex.exec(text)) !== null) {
    const block = match[1].trim();
    if (largest === null || block.length > largest.length) largest = block;
  }
  return largest;
}

const LANG_TO_NAME: Record<string, string> = {
  javascript: 'handler.js',
  js: 'handler.js',
  typescript: 'index.ts',
  ts: 'index.ts',
  json: 'data.json',
  markdown: 'README.md',
  md: 'README.md',
  yaml: 'config.yml',
  yml: 'config.yml',
  python: 'handler.py',
  py: 'handler.py',
};

const PATH_COMMENT = /^(?:\/\/|<!--|#|%)\s*([\w./-]+\.[\w]+)\s*(?:-->)?\s*$/;

function looksLikeMarkdown(content: string): boolean {
  const head = content.slice(0, 400);
  return /^<!--|^#{1,3}\s|\*\*.+\*\*/m.test(head) || /^\|.+\|$/m.test(head);
}

function extractCodeBlocks(text: string): Array<{ path: string; content: string }> {
  const raw: Array<{ info: string; content: string }> = [];
  const regex = /```([^\n`]*)\n([\s\S]*?)```/g;
  let match;
  while ((match = regex.exec(text)) !== null) {
    raw.push({ info: match[1].trim(), content: match[2].trim() });
  }

  const blocks: Array<{ path: string; content: string }> = [];
  const used = new Set<string>();
  const docParts: string[] = [];
  let docAnchor = -1;
  let unnamed = 0;

  const claim = (base: string): string => {
    let candidate = base;
    let n = 1;
    while (used.has(candidate)) {
      candidate = base.replace(/(\.[\w]+)$/, `-${n}$1`);
      n++;
    }
    used.add(candidate);
    return candidate;
  };

  for (const { info, content: rawContent } of raw) {
    let content = rawContent;
    let path = '';

    // Path on the fence line: ```js:handler.js or a bare ```handler.js
    const colon = /^[\w.+#-]+:(.+)$/.exec(info);
    if (colon) path = colon[1].trim();
    else if (/^[\w./-]+\.[\w]+$/.test(info)) path = info;

    // Path as a first-line comment (//, <!-- -->, #)
    const firstLine = content.split('\n', 1)[0].trim();
    if (!path) {
      const m = PATH_COMMENT.exec(firstLine);
      if (m) path = m[1];
    }
    if (path && PATH_COMMENT.test(firstLine)) {
      content = content.split('\n').slice(1).join('\n').trim();
    }

    if (path) {
      // Explicitly named docs keep their own name
      blocks.push({ path: claim(path), content });
      continue;
    }

    const lang = info.toLowerCase().split(/[:\s]/)[0];
    if (lang === 'markdown' || lang === 'md' || (!LANG_TO_NAME[lang] && looksLikeMarkdown(content))) {
      // Unnamed doc chunks merge into ONE README.md, in order
      docParts.push(content);
      if (docAnchor < 0) docAnchor = blocks.length;
    } else if (LANG_TO_NAME[lang]) {
      blocks.push({ path: claim(LANG_TO_NAME[lang]), content });
    } else {
      blocks.push({ path: claim(`file-${unnamed}.txt`), content });
      unnamed++;
    }
  }

  if (docParts.length) {
    blocks.splice(docAnchor, 0, { path: claim('README.md'), content: docParts.join('\n\n') });
  }

  return blocks;
}
