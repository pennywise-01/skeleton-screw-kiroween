export function demoAgentResponse(
  outputSchema: 'files' | 'code' | 'report',
  task: string,
  context?: string,
) {
  if (outputSchema === 'files') {
    return { files: LAMBDA_FILES, explanation: 'Demo mode: cached Lambda files.' };
  }
  if (outputSchema === 'report') {
    return { report: '# Demo Report\n\nThis is a cached demo-mode report.', explanation: 'Demo mode.' };
  }
  // outputSchema === 'code': a11y fix vs lambda spec
  const isFix = (context ?? '').includes('Issues to fix') || task.includes('Fix these accessibility');
  return isFix
    ? { code: FIXED_COMPONENT, explanation: 'Demo mode: cached fixed component.' }
    : { code: LAMBDA_SPEC, explanation: 'Demo mode: cached spec.' };
}



export function demoScanFindings(files: Array<{ name: string; content: string }>) {
  // Haunt the first file with an <img> that lacks alt — mirrors the example fixture.
  // (The fixed fixture has alt=, so re-scans come back clean.)
  const target = files.find(
    (f) => !f.name.includes('node_modules') && f.content.includes('<img') && !f.content.includes('alt='),
  );
  if (!target) return [];
  return [
    {
      file: target.name,
      line: 8,
      col: 7,
      ruleId: 'jsx-a11y/alt-text',
      severity: 'error' as const,
      message:
        'img elements must have an alt prop, either with meaningful text, or an empty string for decorative images.',
    },
    {
      file: target.name,
      line: 10,
      col: 7,
      ruleId: 'jsx-a11y/anchor-is-valid',
      severity: 'error' as const,
      message: 'The href attribute requires a valid value to be accessible.',
    },
    {
      file: target.name,
      line: 10,
      col: 7,
      ruleId: 'jsx-a11y/anchor-ambiguous-text',
      severity: 'warning' as const,
      message: 'Ambiguous text within anchor. Provide descriptive link text for screen readers.',
    },
  ];
}
